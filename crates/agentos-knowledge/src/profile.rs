//! Automatic project profile.
//!
//! The user is never asked whether a repository is greenfield or existing. The profile
//! is a deterministic function of files and git metadata. Missing signals are recorded
//! as `present: false`; absence is not turned into a business fact.
//!
//! Confidence weights are a fixed formula so repeated runs agree. They are not a
//! calibrated probability and they are not a target to optimize.

use std::fs;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::error::KnowledgeError;
use crate::model::ProvenanceKind;
use crate::walk::{self, SourceFile};

/// File name of the derived profile inside `.agentos/`.
pub const PROFILE_FILE: &str = "project-profile.json";

/// Confidence written for an empty tree. Emptiness is observed; calling it greenfield is a convention.
pub const CONFIDENCE_EMPTY_MILLIS: u16 = 500;
/// Base confidence once at least one content signal is present.
pub const CONFIDENCE_BASE_MILLIS: u16 = 600;
/// Added for each present signal (git included) when the tree is not empty.
pub const CONFIDENCE_PER_SIGNAL_MILLIS: u16 = 50;

const SIGNALS: &[&str] = &[
    "git",
    "git_history",
    "source_files",
    "manifests",
    "tests",
    "docs",
    "specs",
    "database",
    "api",
    "ci",
    "container",
];

/// Whether the repository is primarily ahead of code, already code, or both.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum Classification {
    /// Requirements or an empty tree, without a substantial implementation.
    Greenfield,
    /// Substantial source, without a specification artifact.
    Existing,
    /// Substantial source and specification artifacts together.
    Hybrid,
}

impl Classification {
    /// Stable wire name (`GREENFIELD`, `EXISTING`, `HYBRID`).
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Greenfield => "GREENFIELD",
            Self::Existing => "EXISTING",
            Self::Hybrid => "HYBRID",
        }
    }
}

/// How far the repository has progressed, from the signals that are present.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum Maturity {
    /// No content signals. Git metadata alone does not count.
    Empty,
    /// Specs or requirements exist and there is no substantial source.
    Specified,
    /// Scaffolding (manifest, docs, CI, container) without substantial source or specs.
    Skeleton,
    /// Substantial source that does not yet have tests plus docs or CI.
    Developing,
    /// Substantial source, tests, and docs or CI.
    Established,
    /// Established, plus CI or a container, plus a database or API definition, and docs.
    Mature,
}

impl Maturity {
    /// Stable wire name (`EMPTY`, `SPECIFIED`, …).
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Empty => "EMPTY",
            Self::Specified => "SPECIFIED",
            Self::Skeleton => "SKELETON",
            Self::Developing => "DEVELOPING",
            Self::Established => "ESTABLISHED",
            Self::Mature => "MATURE",
        }
    }
}

/// One detection signal. Absent signals are kept so the evidence list is complete.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Signal {
    /// Stable signal name.
    pub name: String,
    /// Whether any evidence was found.
    pub present: bool,
    /// Relative paths (or `.git`) that justify the signal, sorted.
    pub evidence: Vec<String>,
}

/// Derived project profile. Safe to delete; `init` and `scan` rewrite it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ProjectProfile {
    /// Greenfield, existing, or hybrid.
    pub classification: Classification,
    /// Empty through mature.
    pub maturity: Maturity,
    /// Thousandths. See the constants on this module.
    pub confidence_millis: u16,
    /// True when the classification is a convention rather than a decisive observation.
    pub uncertain: bool,
    /// The profile is generated by AgentOS from observed signals.
    pub provenance_kind: ProvenanceKind,
    /// Every known signal, in a fixed order, present or not.
    pub signals: Vec<Signal>,
}

/// What [`write_profile`] did to `.agentos/project-profile.json`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProfileWrite {
    /// The file was created.
    Created,
    /// The bytes were already equal to this run.
    Existing,
    /// The bytes changed and the file was replaced.
    Updated,
}

impl ProfileWrite {
    /// Status word used by `agentos init`.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Created => "created",
            Self::Existing => "exists",
            Self::Updated => "updated",
        }
    }
}

/// `<root>/.agentos/project-profile.json`.
pub fn profile_path(root: &Path) -> PathBuf {
    root.join(agentos_core::state::STATE_DIR).join(PROFILE_FILE)
}

/// Detects the profile of `root` without writing it.
pub fn detect(root: &Path) -> Result<ProjectProfile, KnowledgeError> {
    let files = walk::list_sources(root)?;
    Ok(detect_from(root, &files))
}

/// Builds a profile from an already-walked file list.
pub fn detect_from(root: &Path, files: &[SourceFile]) -> ProjectProfile {
    let mut evidence: Vec<(&str, Vec<String>)> =
        SIGNALS.iter().map(|name| (*name, Vec::new())).collect();
    let git = git_evidence(root);
    push(&mut evidence, "git", git.present.then(|| ".git".to_owned()));
    if git.history {
        push(&mut evidence, "git_history", Some(".git/HEAD".to_owned()));
    }
    for file in files {
        if let Some(signal) = classify_path(&file.relative) {
            push(&mut evidence, signal, Some(file.relative.clone()));
        }
    }
    for (_, paths) in &mut evidence {
        paths.sort();
        paths.dedup();
    }
    let present = |name: &str| {
        evidence
            .iter()
            .find(|(n, _)| *n == name)
            .is_some_and(|(_, paths)| !paths.is_empty())
    };
    let source = present("source_files");
    let specs = present("specs");
    let tests = present("tests");
    let docs = present("docs");
    let ci = present("ci");
    let container = present("container");
    let database = present("database");
    let api = present("api");
    let content = SIGNALS
        .iter()
        .filter(|name| !matches!(**name, "git" | "git_history") && present(name))
        .count();

    let classification = if source && specs {
        Classification::Hybrid
    } else if source {
        Classification::Existing
    } else {
        Classification::Greenfield
    };
    let maturity = if content == 0 {
        Maturity::Empty
    } else if !source && specs {
        Maturity::Specified
    } else if !source {
        Maturity::Skeleton
    } else if source && tests && docs && (ci || container) && (database || api) {
        Maturity::Mature
    } else if source && tests && (docs || ci) {
        Maturity::Established
    } else {
        Maturity::Developing
    };
    let present_count = evidence
        .iter()
        .filter(|(_, paths)| !paths.is_empty())
        .count();
    let confidence_millis = if maturity == Maturity::Empty {
        CONFIDENCE_EMPTY_MILLIS
    } else {
        CONFIDENCE_BASE_MILLIS
            .saturating_add(
                u16::try_from(present_count).unwrap_or(u16::MAX) * CONFIDENCE_PER_SIGNAL_MILLIS,
            )
            .min(1000)
    };
    ProjectProfile {
        classification,
        maturity,
        confidence_millis,
        uncertain: maturity == Maturity::Empty,
        provenance_kind: ProvenanceKind::Generated,
        signals: evidence
            .into_iter()
            .map(|(name, paths)| Signal {
                name: name.to_owned(),
                present: !paths.is_empty(),
                evidence: paths,
            })
            .collect(),
    }
}

fn push(evidence: &mut [(&str, Vec<String>)], name: &str, path: Option<String>) {
    let Some(path) = path else {
        return;
    };
    if let Some((_, paths)) = evidence.iter_mut().find(|(n, _)| *n == name) {
        paths.push(path);
    }
}

/// Canonical pretty JSON, trailing newline, no timestamp.
pub fn to_json(profile: &ProjectProfile) -> String {
    let mut rendered = serde_json::to_string_pretty(profile).expect("project profile serializes");
    rendered.push('\n');
    rendered
}

/// Writes the profile if the bytes changed. Creates `.agentos/` when needed.
pub fn write_profile(root: &Path) -> Result<(ProjectProfile, ProfileWrite), KnowledgeError> {
    let profile = detect(root)?;
    let path = profile_path(root);
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    let rendered = to_json(&profile);
    let status = if path.is_file() {
        let current = fs::read_to_string(&path)?;
        if current == rendered {
            ProfileWrite::Existing
        } else {
            fs::write(&path, &rendered)?;
            ProfileWrite::Updated
        }
    } else {
        fs::write(&path, &rendered)?;
        ProfileWrite::Created
    };
    Ok((profile, status))
}

/// Reads a previously written profile.
pub fn read_profile(root: &Path) -> Result<ProjectProfile, KnowledgeError> {
    let path = profile_path(root);
    let text = fs::read_to_string(&path)?;
    serde_json::from_str(&text).map_err(|err| KnowledgeError::Profile {
        path,
        message: err.to_string(),
    })
}

struct GitEvidence {
    present: bool,
    history: bool,
}

fn git_evidence(root: &Path) -> GitEvidence {
    let git = root.join(".git");
    if !git.exists() {
        return GitEvidence {
            present: false,
            history: false,
        };
    }
    let git_dir = if git.is_dir() {
        git
    } else {
        match resolve_gitdir(&git) {
            Some(dir) => dir,
            None => {
                return GitEvidence {
                    present: true,
                    history: false,
                };
            }
        }
    };
    GitEvidence {
        present: true,
        history: head_has_commit(&git_dir),
    }
}

fn resolve_gitdir(git_file: &Path) -> Option<PathBuf> {
    let text = fs::read_to_string(git_file).ok()?;
    let rest = text.trim().strip_prefix("gitdir:")?.trim();
    let path = PathBuf::from(rest);
    let resolved = if path.is_absolute() {
        path
    } else {
        git_file.parent()?.join(path)
    };
    resolved.is_dir().then_some(resolved)
}

fn head_has_commit(git_dir: &Path) -> bool {
    let Ok(head) = fs::read_to_string(git_dir.join("HEAD")) else {
        return false;
    };
    let head = head.trim();
    if let Some(refname) = head.strip_prefix("ref:") {
        let refname = refname.trim();
        let ref_file = git_dir.join(refname);
        if ref_file.is_file() && fs::read(&ref_file).is_ok_and(|b| !b.is_empty()) {
            return true;
        }
        packed_refs_has(git_dir, refname)
    } else {
        head.len() == 40 && head.chars().all(|c| c.is_ascii_hexdigit())
    }
}

fn packed_refs_has(git_dir: &Path, refname: &str) -> bool {
    let Ok(text) = fs::read_to_string(git_dir.join("packed-refs")) else {
        return false;
    };
    text.lines().any(|line| {
        let line = line.trim();
        !line.is_empty() && !line.starts_with('#') && line.ends_with(refname)
    })
}

fn classify_path(relative: &str) -> Option<&'static str> {
    if is_ci(relative) {
        return Some("ci");
    }
    if is_container(relative) {
        return Some("container");
    }
    if is_manifest(relative) {
        return Some("manifests");
    }
    if is_api(relative) {
        return Some("api");
    }
    if is_database(relative) {
        return Some("database");
    }
    if is_test(relative) {
        return Some("tests");
    }
    if is_source(relative) {
        return Some("source_files");
    }
    if is_spec(relative) {
        return Some("specs");
    }
    if is_doc(relative) {
        return Some("docs");
    }
    None
}

fn file_name(relative: &str) -> &str {
    relative.rsplit('/').next().unwrap_or(relative)
}

fn is_test(relative: &str) -> bool {
    crate::id::is_test_path(relative) && is_source_extension(file_name(relative))
}

fn is_source(relative: &str) -> bool {
    is_source_extension(file_name(relative)) && !crate::id::is_test_path(relative)
}

fn is_source_extension(name: &str) -> bool {
    const EXTS: &[&str] = &[
        ".py", ".pyi", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".rs", ".go", ".java", ".rb",
        ".kt", ".php", ".c", ".h", ".cpp", ".hpp",
    ];
    EXTS.iter().any(|ext| name.ends_with(ext))
}

fn is_spec(relative: &str) -> bool {
    let name = file_name(relative);
    let lower = name.to_ascii_lowercase();
    let spec_dir = relative.split('/').any(|p| p == "spec" || p == "specs");
    spec_dir
        || lower.contains("requirement")
        || lower == "spec.md"
        || lower == "prd.md"
        || lower.ends_with(".spec.md")
}

fn is_doc(relative: &str) -> bool {
    let lower = file_name(relative).to_ascii_lowercase();
    lower.ends_with(".md") || lower.ends_with(".rst")
}

fn is_manifest(relative: &str) -> bool {
    const NAMES: &[&str] = &[
        "pyproject.toml",
        "setup.py",
        "setup.cfg",
        "requirements.txt",
        "pipfile",
        "package.json",
        "cargo.toml",
        "go.mod",
        "pom.xml",
        "build.gradle",
        "build.gradle.kts",
        "gemfile",
        "composer.json",
        "package.swift",
        "mix.exs",
        "pubspec.yaml",
    ];
    let name = file_name(relative).to_ascii_lowercase();
    NAMES.contains(&name.as_str())
}

fn is_database(relative: &str) -> bool {
    let name = file_name(relative).to_ascii_lowercase();
    name.ends_with(".sql")
        || name == "schema.prisma"
        || name == "alembic.ini"
        || relative
            .split('/')
            .any(|p| p == "migrations" || p == "alembic")
}

fn is_api(relative: &str) -> bool {
    let name = file_name(relative).to_ascii_lowercase();
    matches!(
        name.as_str(),
        "openapi.yaml"
            | "openapi.yml"
            | "openapi.json"
            | "swagger.yaml"
            | "swagger.yml"
            | "swagger.json"
            | "schema.graphql"
    ) || name.ends_with(".proto")
        || name.ends_with(".graphql")
}

fn is_ci(relative: &str) -> bool {
    let name = file_name(relative);
    relative.starts_with(".github/workflows/")
        || name == ".gitlab-ci.yml"
        || name == "Jenkinsfile"
        || name == "azure-pipelines.yml"
        || name == ".travis.yml"
        || relative.starts_with(".circleci/")
}

fn is_container(relative: &str) -> bool {
    let name = file_name(relative);
    name == "Dockerfile"
        || name.starts_with("Dockerfile.")
        || name == "Containerfile"
        || name.starts_with("docker-compose.")
        || name == "compose.yaml"
        || name == "compose.yml"
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::process::Command;

    fn touch(dir: &Path, rel: &str, body: &str) {
        let path = dir.join(rel);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).unwrap();
        }
        fs::write(path, body).unwrap();
    }

    #[test]
    fn empty_tree_is_uncertain_greenfield() {
        let tmp = tempfile::tempdir().unwrap();
        touch(tmp.path(), "NOTES.txt", "not started\n");
        let profile = detect(tmp.path()).unwrap();
        assert_eq!(profile.classification, Classification::Greenfield);
        assert_eq!(profile.maturity, Maturity::Empty);
        assert!(profile.uncertain);
        assert_eq!(profile.confidence_millis, CONFIDENCE_EMPTY_MILLIS);
        assert_eq!(profile.provenance_kind, ProvenanceKind::Generated);
        assert!(profile.signals.iter().all(|s| !s.present));
    }

    #[test]
    fn specs_without_source_are_specified() {
        let tmp = tempfile::tempdir().unwrap();
        touch(tmp.path(), "README.md", "# Plan\n");
        touch(tmp.path(), "docs/spec/requirements.md", "# Requirements\n");
        touch(tmp.path(), "pyproject.toml", "[project]\nname='x'\n");
        let profile = detect(tmp.path()).unwrap();
        assert_eq!(profile.classification, Classification::Greenfield);
        assert_eq!(profile.maturity, Maturity::Specified);
        assert!(!profile.uncertain);
        assert_eq!(profile.confidence_millis, 750);
        let specs = profile.signals.iter().find(|s| s.name == "specs").unwrap();
        assert_eq!(specs.evidence, vec!["docs/spec/requirements.md".to_owned()]);
    }

    #[test]
    fn source_and_tests_and_docs_are_established() {
        let tmp = tempfile::tempdir().unwrap();
        touch(tmp.path(), "README.md", "# Orders\n");
        touch(tmp.path(), "pyproject.toml", "[project]\nname='x'\n");
        touch(
            tmp.path(),
            "app/orders/service.py",
            "class OrderService:\n    pass\n",
        );
        touch(
            tmp.path(),
            "tests/test_orders.py",
            "def test_ok():\n    pass\n",
        );
        let profile = detect(tmp.path()).unwrap();
        assert_eq!(profile.classification, Classification::Existing);
        assert_eq!(profile.maturity, Maturity::Established);
        assert_eq!(profile.confidence_millis, 800);
    }

    #[test]
    fn source_plus_specs_is_hybrid() {
        let tmp = tempfile::tempdir().unwrap();
        touch(tmp.path(), "README.md", "# Billing\n");
        touch(tmp.path(), "docs/spec/billing.md", "# Billing spec\n");
        touch(tmp.path(), "pyproject.toml", "[project]\nname='x'\n");
        touch(
            tmp.path(),
            "app/billing/service.py",
            "class BillingService:\n    pass\n",
        );
        touch(
            tmp.path(),
            "tests/test_billing.py",
            "def test_ok():\n    pass\n",
        );
        let profile = detect(tmp.path()).unwrap();
        assert_eq!(profile.classification, Classification::Hybrid);
        assert_eq!(profile.maturity, Maturity::Established);
        assert_eq!(profile.confidence_millis, 850);
    }

    #[test]
    fn full_signals_are_mature_existing() {
        let tmp = tempfile::tempdir().unwrap();
        touch(tmp.path(), "README.md", "# S\n");
        touch(tmp.path(), "pyproject.toml", "[project]\nname='x'\n");
        touch(tmp.path(), "app/svc.py", "x = 1\n");
        touch(
            tmp.path(),
            "tests/test_svc.py",
            "def test_ok():\n    pass\n",
        );
        touch(tmp.path(), "Dockerfile", "FROM python:3.11\n");
        touch(tmp.path(), ".github/workflows/ci.yml", "name: ci\n");
        touch(tmp.path(), "openapi.yaml", "openapi: 3.0.3\n");
        touch(tmp.path(), "schema.sql", "CREATE TABLE t(id INT);\n");
        let profile = detect(tmp.path()).unwrap();
        assert_eq!(profile.classification, Classification::Existing);
        assert_eq!(profile.maturity, Maturity::Mature);
        assert_eq!(profile.confidence_millis, 1000);
    }

    #[test]
    fn repeated_detection_is_byte_identical() {
        let tmp = tempfile::tempdir().unwrap();
        touch(tmp.path(), "app/svc.py", "x = 1\n");
        assert_eq!(
            to_json(&detect(tmp.path()).unwrap()),
            to_json(&detect(tmp.path()).unwrap())
        );
    }

    #[test]
    fn write_profile_is_idempotent() {
        let tmp = tempfile::tempdir().unwrap();
        touch(tmp.path(), "NOTES.txt", "x\n");
        let (_, first) = write_profile(tmp.path()).unwrap();
        let (_, second) = write_profile(tmp.path()).unwrap();
        assert_eq!(first, ProfileWrite::Created);
        assert_eq!(second, ProfileWrite::Existing);
        assert_eq!(
            read_profile(tmp.path()).unwrap(),
            detect(tmp.path()).unwrap()
        );
    }

    #[test]
    fn git_init_is_not_history_until_a_commit_exists() {
        let tmp = tempfile::tempdir().unwrap();
        let root = tmp.path();
        touch(root, "NOTES.txt", "x\n");
        let status = Command::new("git")
            .args(["init", "-q"])
            .current_dir(root)
            .status()
            .unwrap();
        assert!(status.success());
        let profile = detect(root).unwrap();
        assert!(profile.signals.iter().any(|s| s.name == "git" && s.present));
        assert!(
            profile
                .signals
                .iter()
                .any(|s| s.name == "git_history" && !s.present)
        );
        assert_eq!(profile.maturity, Maturity::Empty);

        fs::write(root.join("README.md"), "# Hi\n").unwrap();
        let commit = Command::new("git")
            .args([
                "-c",
                "user.email=test@example.com",
                "-c",
                "user.name=test",
                "add",
                "README.md",
            ])
            .current_dir(root)
            .status()
            .unwrap();
        assert!(commit.success());
        let commit = Command::new("git")
            .args([
                "-c",
                "user.email=test@example.com",
                "-c",
                "user.name=test",
                "commit",
                "-q",
                "-m",
                "init",
            ])
            .current_dir(root)
            .status()
            .unwrap();
        assert!(commit.success());
        let profile = detect(root).unwrap();
        assert!(
            profile
                .signals
                .iter()
                .any(|s| s.name == "git_history" && s.present)
        );
        assert_eq!(profile.maturity, Maturity::Skeleton);
    }
}
